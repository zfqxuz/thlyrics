import { chromium } from 'playwright';
import fs from 'node:fs'; import path from 'node:path';
const root=(process.env.HOME||'/home/zfq')+'/.cache/ms-playwright';
const dirs=fs.readdirSync(root).filter(d=>d.startsWith('chromium_headless_shell-')).sort();
const chrome=path.join(root,dirs[dirs.length-1],'chrome-headless-shell-linux64','chrome-headless-shell');
const libPath=['root/usr/lib/x86_64-linux-gnu','root/lib/x86_64-linux-gnu','root/usr/lib','root/lib'].map(p=>path.join('/home/zfq/qqbot/thlyrics/.e2e',p)).join(':');
const b=await chromium.launch({executablePath:chrome,args:['--no-sandbox'],env:{...process.env,LD_LIBRARY_PATH:libPath}});
const page=await b.newPage({viewport:{width:420,height:900}});
page.on('pageerror',e=>console.log('[pageerror]',e.message));
await page.goto('http://127.0.0.1:8848/?v=ui',{waitUntil:'domcontentloaded'});
await page.waitForTimeout(800);
await page.evaluate(() => {
  const S = JSON.parse(localStorage.getItem('thlyrics.tool.v1') || '{}');
  S.userLocale='zh-CN'; S.learnLang='ja';
  S.imp = { i999: { id:'i999', nid:999, src:'netease', title:'テスト', artist:'x', album:'', cover:'',
    lines:[{t:1,text:'もう ずっと いつも'},{t:5,text:'少し まだ そう'}], langs:['ja'], lineLangs:['ja','ja'], primaryLang:'ja', at: Date.now() } };
  localStorage.setItem('thlyrics.tool.v1', JSON.stringify(S));
});
await page.goto('http://127.0.0.1:8848/#/learn',{waitUntil:'domcontentloaded'});
await page.waitForTimeout(4000);
const learn = await page.locator('#view-learn').innerText();
console.log('learn 前 12 行:', learn.split('\n').slice(0,12).join(' | '));
console.log('filter pills:', await page.locator('#view-learn .fpill').allTextContents());
await page.goto('http://127.0.0.1:8848/#/songs',{waitUntil:'domcontentloaded'});
await page.waitForTimeout(1500);
console.log('songs pills:', await page.locator('#view-songs .fpill').allTextContents());
await page.locator('#view-songs .fpill').first().click();
await page.waitForTimeout(400);
console.log('picker:', (await page.locator('#dlg').innerText()).replace(/\n/g,' | ').slice(0,160));
await b.close();
